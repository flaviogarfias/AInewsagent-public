"""Immutable delivery snapshot: transport existing artifacts without rerendering."""

from __future__ import annotations

from dataclasses import dataclass
from hashlib import sha256
from pathlib import Path
from typing import Mapping


@dataclass(frozen=True)
class DeliveryBundle:
    html_body: str
    pdf_bytes: bytes
    pdf_name: str
    html_sha256: str
    pdf_sha256: str


def _paths(artifacts: Mapping[str, str | Path]) -> tuple[Path, Path]:
    return Path(artifacts["html"]), Path(artifacts["pdf"])


def prepare_delivery_bundle(artifacts: Mapping[str, str | Path]) -> DeliveryBundle:
    """Snapshot the exact generated bytes; do not call either renderer."""
    html_path, pdf_path = _paths(artifacts)
    html = html_path.read_bytes()
    pdf = pdf_path.read_bytes()
    if not html or not html.decode("utf-8").lstrip().lower().startswith("<!doctype html>"):
        raise ValueError("invalid HTML artifact")
    if not pdf_path.name.lower().endswith(".pdf") or not pdf.startswith(b"%PDF"):
        raise ValueError("invalid PDF artifact")
    return DeliveryBundle(html.decode("utf-8"), pdf, pdf_path.name,
                          sha256(html).hexdigest(), sha256(pdf).hexdigest())


def verify_delivery_bundle(bundle: DeliveryBundle, artifacts: Mapping[str, str | Path]) -> None:
    """Fail closed if an artifact changed between review and upload."""
    html_path, pdf_path = _paths(artifacts)
    if sha256(html_path.read_bytes()).hexdigest() != bundle.html_sha256:
        raise ValueError("HTML changed after bundle preparation")
    if sha256(pdf_path.read_bytes()).hexdigest() != bundle.pdf_sha256:
        raise ValueError("PDF changed after bundle preparation")
